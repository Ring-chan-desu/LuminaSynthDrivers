/**
 * @brief 发送指令
 * 
 * @param Command 需要发送的指令
 */
void Screen_SendCommand(uint8_t Command)
{
    uint8_t CommandBuffer[2] = {0x00,Command};
    HAL_I2C_Master_Transmit(&hi2c1,ADDRESS,CommandBuffer,2,HAL_MAX_DELAY);
}

