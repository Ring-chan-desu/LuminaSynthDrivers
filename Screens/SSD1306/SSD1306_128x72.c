/**
 * @brief 将数字处理成能在显示屏上显示的版本,返回一个带页地址和移位数的结构体
 * 
 * @param Number 要处理的数字
 * @note Pixel类型定义详见头文件
 */
Pixel Screen_NumberProcess(uint8_t Number)
{
    Pixel pixel;
    pixel.Page = ( Number / 8 ); //求页地址,应为0. . .7
    pixel.Offset = Number % 8;//求本页偏移量

    return pixel;
}

