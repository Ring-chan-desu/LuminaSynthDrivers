/**
 * @brief 三角波测试数组初始化
 * 
 * @param TestArray 传入的待设置的数组的指针
 */
void Screen_InitTestArray(uint8_t* TestArray)
{
    for (int i = 0; i < 128; i++) {
        // 三角波1：周期32，幅度0..15
        uint8_t t1 = i % 32;
        if (t1 >= 16) t1 = 31 - t1;

        // 三角波2：周期20，幅度0..9
        uint8_t t2 = i % 20;
        if (t2 >= 10) t2 = 19 - t2;

        // 组合并缩放到 0..63（noise 范围 -1..1）
        int v = (t1 * 3) + (t2 * 2) + (rand() % 3 - 1);

        // 限制到 0..63
        if (v < 0) v = 0;
        if (v > 63) v = 63;

        TestArray[i] = (uint8_t)v;
    }
}

